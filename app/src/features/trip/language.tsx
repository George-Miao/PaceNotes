const UiLanguageContext = createContext<TripLanguage>("en");
const TripLanguageContext = createContext<TripLanguage>("en");

export function UiLanguageProvider({
  language,
  children,
}: {
  language: TripLanguage;
  children: ReactNode;
}) {
  useEffect(() => {
    const previous = document.documentElement.lang;
    document.documentElement.lang = languageTag(language);
    return () => {
      document.documentElement.lang = previous;
    };
  }, [language]);
  return <UiLanguageContext value={language}>{children}</UiLanguageContext>;
}

export function TripLanguageProvider({
  language,
  children,
}: {
  language: TripLanguage;
  children: ReactNode;
}) {
  return <TripLanguageContext value={language}>{children}</TripLanguageContext>;
}

export function useUiLanguage(): TripLanguage {
  return useContext(UiLanguageContext);
}

export function useTripLanguage(): TripLanguage {
  return useContext(TripLanguageContext);
}

export function useTripText(): TripText {
  const language = useUiLanguage();
  return useMemo(() => createTripText(language), [language]);
}

export function createTripText(language: TripLanguage): TripText {
  const messages = translations[language];
  return (key, values) => format(messages[key] ?? english[key], values);
}

export function languageTag(language: TripLanguage): string {
  return language;
}
export function formatTravelDuration(totalMinutes: number, language: TripLanguage): string {
  const hours = Math.floor(totalMinutes / 60);
  const minutes = totalMinutes % 60;
  const formatUnit = (value: number, unit: "hour" | "minute") =>
    new Intl.NumberFormat(languageTag(language), {
      style: "unit",
      unit,
      unitDisplay: "short",
    }).format(value);
  return [hours ? formatUnit(hours, "hour") : "", minutes ? formatUnit(minutes, "minute") : ""]
    .filter(Boolean)
    .join(" ");
}

export function travelModeLabel(language: TripLanguage, mode: TravelMode): string {
  const text = createTripText(language);
  if (mode === "DRIVING") return text("car");
  if (mode === "TRANSIT") return text("publicTransport");
  return text("walk");
}

function format(message: string, values?: Record<string, string | number>): string {
  if (!values) return message;
  return message.replace(/\{(\w+)\}/g, (placeholder, key: string) =>
    Object.hasOwn(values, key) ? String(values[key]) : placeholder,
  );
}
